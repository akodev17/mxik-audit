const nu = (v: number): string => fmtNumber('uz', v);
const nr = (v: number): string => fmtNumber('ru', v);
const rows = (v: number): string => `${nr(v)} ${pluralRu(v, 'строка', 'строки', 'строк')}`;

/** Seconds as "3 daqiqa" / "40 soniya". */
const etaUz = (s: number): string => (s >= 90 ? `${nu(Math.round(s / 60))} daqiqa` : `${nu(Math.max(5, Math.round(s / 5) * 5))} soniya`);
const etaRu = (s: number): string => {
  if (s >= 90) { const m = Math.round(s / 60); return `${nr(m)} ${pluralRu(m, 'минута', 'минуты', 'минут')}`; }
  const sec = Math.max(5, Math.round(s / 5) * 5);
  return `${nr(sec)} ${pluralRu(sec, 'секунда', 'секунды', 'секунд')}`;
};


// The W2/W3 checklist in README.md: one row per server action, route handler and page read the
// registry takes over. Generated, so it cannot drift from the registry; ticks are kept.
// Regenerate: npx tsx packages/contracts/src/checklist.ts --write   (from the repository root)
import { readFileSync, writeFileSync } from 'node:fs';
import { MODULES } from './endpoint';
import { allEndpoints } from './registry';

export const README = 'packages/contracts/README.md';
const BEGIN = '<!-- checklist:begin (generated by src/checklist.ts; tick the boxes, do not edit the rest) -->';
const END = '<!-- checklist:end -->';

const KIND: Record<string, string> = { action: 'action', route: 'route', page: 'page' };

function oldName(replaces: string): string {
  const [kind, rest] = [replaces.slice(0, replaces.indexOf(':')), replaces.slice(replaces.indexOf(':') + 1)];
  return `${KIND[kind] ?? kind} \`${rest}\``;
}

/** Row key for keeping ticks: the old thing plus the operation id. */
const rowKey = (line: string): string => line.replace(/\[[ x]\]/g, '[ ]');

export function renderChecklist(previous = ''): string {
  const ticked = new Map(previous.split('\n').filter((l) => l.startsWith('|')).map((l) => [rowKey(l), l]));
  const out: string[] = [BEGIN, ''];
  const all = allEndpoints();
  out.push(`${all.length} operations; ${all.filter((e) => e.provisional).length} with a provisional shape (⚠, listed below the table).`, '');
  out.push('| Module | Operations |', '|---|---|');
  for (const m of MODULES) out.push(`| ${m} | ${all.filter((e) => e.module === m).length} |`);
  out.push('');
  for (const m of MODULES) {
    out.push(`### ${m}`, '', '| W2 | W3 | Replaces | Operation | Endpoint | Auth |', '|---|---|---|---|---|---|');
    for (const e of all.filter((x) => x.module === m)) {
      const auth = e.auth === 'session' ? `session (${e.role}${e.noDemo ? ', no demo' : ''})` : e.auth;
      for (const r of e.replaces) {
        const line = `| [ ] | [ ] | ${oldName(r)} | \`${e.operationId}\`${e.provisional ? ' ⚠' : ''} | \`${e.method} ${e.path}\` | ${auth} |`;
        out.push(ticked.get(rowKey(line)) ?? line);
      }
    }
    out.push('');
  }
  out.push('### Provisional shapes (page data assembled in server components today; W2 confirms or changes)', '');
  for (const e of all.filter((x) => x.provisional)) out.push(`- \`${e.operationId}\`: ${e.provisional}.`);
  out.push('', END);
  return out.join('\n');
}

/** The generated part of a README, or '' when the markers are missing. */
export function checklistOf(readme: string): string {
  const start = readme.indexOf(BEGIN);
  const end = readme.indexOf(END);
  return start < 0 || end < 0 ? '' : readme.slice(start, end + END.length);
}

export function writeChecklist(path = README): void {
  const readme = readFileSync(path, 'utf8');
  const current = checklistOf(readme);
  const next = renderChecklist(current);
  writeFileSync(path, current ? readme.replace(current, next) : `${readme.trimEnd()}\n\n${next}\n`);
}

if (process.argv.includes('--write')) {
  writeChecklist();
  console.log(`updated ${README}`);
}

// Emits src/core/normalize/units.generated.ts from the portal's own unit
// reference, so the canonical vocabulary is derived rather than invented.
// Also reports how much of the export's free-text unit column the official
// dictionary actually covers.
// Run: npm run generate:units
import { readFileSync, writeFileSync } from 'node:fs';
import { cyrillicToLatin } from '../src/core/normalize/script.js';
import { stripApostrophes } from '../src/core/normalize/apostrophe.js';

type UnitsFile = {
  apiReference: { id: number; name: string }[];
  canonicalFromExport: [string, number][];
};

const raw = JSON.parse(readFileSync('data/units.json', 'utf8')) as UnitsFile;

const official = raw.apiReference
  .map((u) => ({ id: u.id, cyrillic: u.name.trim(), latin: cyrillicToLatin(u.name.trim()).toLowerCase() }))
  .sort((a, b) => a.id - b.id);

const key = (s: string): string => stripApostrophes(s.toLowerCase()).replace(/\s+/g, ' ').trim();
const byKey = new Map<string, number>();
for (const u of official) {
  byKey.set(key(u.latin), u.id);
  byKey.set(key(u.cyrillic), u.id);
}

// How many export rows land on an official unit?
let covered = 0;
let uncovered = 0;
const missing: [string, number][] = [];
for (const [unit, count] of raw.canonicalFromExport) {
  if (byKey.has(key(unit))) covered += count;
  else { uncovered += count; missing.push([unit, count]); }
}
missing.sort((a, b) => b[1] - a[1]);

const banner = `// GENERATED by scripts/generate-units.ts — do not edit.
// Source: GET /integration-mxik/references/get/units/all?pageSize=200
// ${official.length} official units. Latin forms are transliterated from the
// Cyrillic originals, which are the portal's canonical spelling.
`;

const body = `${banner}
export type OfficialUnit = {
  /** Stable id from the portal's unit reference. */
  readonly id: number;
  readonly cyrillic: string;
  readonly latin: string;
};

export const OFFICIAL_UNITS: readonly OfficialUnit[] = ${JSON.stringify(official, null, 2)} as const;

export const OFFICIAL_UNIT_IDS = new Set<number>(OFFICIAL_UNITS.map((u) => u.id));
`;

writeFileSync('src/core/normalize/units.generated.ts', body);

console.log(`official units:            ${official.length}`);
console.log(`export unit mentions:      ${(covered + uncovered).toLocaleString()}`);
console.log(`covered by official dict:  ${covered.toLocaleString()} (${((covered / (covered + uncovered)) * 100).toFixed(1)}%)`);
console.log(`uncovered:                 ${uncovered.toLocaleString()} across ${missing.length} distinct strings`);
console.log('\ntop uncovered export unit strings:');
missing.slice(0, 20).forEach(([u, n]) => console.log(`  ${String(n).padStart(7)}  ${JSON.stringify(u)}`));
console.log('\nsample transliterations (validates script.ts on real strings):');
official.slice(0, 14).forEach((u) => console.log(`  ${String(u.id).padStart(4)}  ${u.cyrillic.padEnd(26)} -> ${u.latin}`));
console.log('\nwrote src/core/normalize/units.generated.ts');

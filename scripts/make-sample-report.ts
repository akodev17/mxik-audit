// Freezes an anonymised sample report from a real audit run into
// src/lib/sample-report.generated.ts, for the landing page to embed.
//
// The landing page says the sample is real. It is: these are actual findings the
// pipeline produced. Brand names are masked, because a public page should not
// carry a customer's product list even when the customer is a demo.
// Run: npm run make:sample-report
import '../src/lib/load-env.js';
import { writeFileSync } from 'node:fs';
import { db } from '../src/lib/db.js';
import { lookupCode } from '../src/lib/audit-runner.js';

const ROWS_TO_SHOW = 8;

const catalog = await db.catalog.findFirst({
  where: { status: 'ready' },
  orderBy: { createdAt: 'desc' },
});
if (!catalog) throw new Error('No audited catalogue found.');

const [grouped, riskyRows] = await Promise.all([
  db.finding.groupBy({
    by: ['type'],
    where: { item: { catalogId: catalog.id } },
    _count: { _all: true },
  }),
  db.catalogItem.count({ where: { catalogId: catalog.id, findings: { some: {} } } }),
]);

const counts = new Map(grouped.map((g) => [g.type, g._count._all]));

// Two per type, but never two products of the same kind: a sample that is half
// caviar reads as cherry-picked even when it is not.
const picked: Awaited<ReturnType<typeof db.finding.findMany>> = [];
const seenKinds = new Set<string>();
const kindOf = (name: string): string =>
  (name.split(':')[0] ?? name).toLowerCase().replace(/[^a-z]/g, '').slice(0, 10);

for (const type of ['MISSING', 'NOT_FOUND', 'MISMATCH', 'UNIT_CONFLICT'] as const) {
  const candidates = await db.finding.findMany({
    where: { item: { catalogId: catalog.id }, type },
    orderBy: { confidence: 'desc' },
    include: { item: { select: { rawName: true, existingMxik: true, unit: true, rowIndex: true } } },
  });
  if (candidates.length === 0) continue;

  // One from each end of the confidence range per type. Publishing only the
  // best-scoring rows shows 100% on every line, which misrepresents typical
  // performance and reads as cherry-picked to a sceptical reader. The weakest
  // rows are the ones that prove the tool asks for a human.
  const wanted = [0, candidates.length - 1];
  for (const index of wanted) {
    for (let probe = index; probe < candidates.length; probe++) {
      const c = candidates[probe];
      if (!c) continue;
      const kind = kindOf(c.item.rawName);
      if (seenKinds.has(kind)) continue;
      seenKinds.add(kind);
      picked.push(c);
      break;
    }
  }
}

/** Masks brand names so a public page carries no customer product list. */
function anonymise(name: string): string {
  // Catalogue names are "Subposition: Brand, attributes". Keep the generic head.
  const parts = name.split(':');
  if (parts.length < 2 || !parts[0]) return name;
  const head = parts[0].trim();
  const tail = parts.slice(1).join(':');
  // Preserve pack sizes and percentages; they are why matching is hard.
  const keptDetail = tail.match(/\d+[.,]?\d*\s*(?:kg|g|gr|l|ml|dona|%)/gi);
  return keptDetail ? `${head}: […], ${keptDetail.join(', ')}` : `${head}: […]`;
}

type SampleRow = {
  type: string;
  severity: string;
  productName: string;
  currentMxik: string | null;
  unit: string | null;
  suggestedMxik: string | null;
  suggestedName: string | null;
  confidence: number | null;
  reason: string;
};

const rows: SampleRow[] = [];
for (const f of picked.slice(0, ROWS_TO_SHOW)) {
  const item = (f as typeof f & { item: { rawName: string; existingMxik: string | null; unit: string | null } }).item;
  const detail = f.suggestedMxik ? await lookupCode(f.suggestedMxik) : null;
  rows.push({
    type: f.type,
    severity: f.severity,
    productName: anonymise(item.rawName),
    currentMxik: item.existingMxik,
    unit: item.unit,
    suggestedMxik: f.suggestedMxik,
    suggestedName: detail?.nameUz ? anonymise(detail.nameUz) : null,
    confidence: f.confidence,
    reason: f.reason,
  });
}

const payload = {
  generatedAt: new Date().toISOString().slice(0, 10),
  totalRows: catalog.rowCount,
  riskyRows,
  byType: {
    MISSING: counts.get('MISSING') ?? 0,
    NOT_FOUND: counts.get('NOT_FOUND') ?? 0,
    MISMATCH: counts.get('MISMATCH') ?? 0,
    UNIT_CONFLICT: counts.get('UNIT_CONFLICT') ?? 0,
  },
  rows,
};

const file = `// GENERATED by scripts/make-sample-report.ts — do not edit.
//
// A real audit run, frozen for the landing page. Brand names are masked; the
// codes, confidences and finding types are exactly what the pipeline produced.

export type SampleRow = {
  type: string;
  severity: string;
  productName: string;
  currentMxik: string | null;
  unit: string | null;
  suggestedMxik: string | null;
  suggestedName: string | null;
  confidence: number | null;
  reason: string;
};

export const SAMPLE_REPORT = ${JSON.stringify(payload, null, 2)} as const;
`;

writeFileSync('src/lib/sample-report.generated.ts', file);
console.log(`wrote src/lib/sample-report.generated.ts`);
console.log(`  ${payload.riskyRows} risky of ${payload.totalRows} rows`);
console.log(`  ${rows.length} sample findings across ${Object.keys(payload.byType).length} types`);
rows.forEach((r) => console.log(`    ${r.type.padEnd(14)} ${r.productName.slice(0, 52)}`));
await db.$disconnect();
